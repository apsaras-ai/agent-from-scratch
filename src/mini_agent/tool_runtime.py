"""Chapter 7: schema-aware, policy-gated ASYNC tool runtime.

The executor uses JSON Schema draft 2020-12 (jsonschema dependency). It does
NOT interpret or execute arbitrary model text as Python/shell. Approval is an
explicit server-side grant; MCP-provided annotations are never authoritative.

SECURITY LIMITS: asyncio.wait_for is *cooperative*, NOT a sandbox or a hard
deadline for non-cooperative external operations. In-memory duplicate tracking
is not durable and cannot promise exactly-once external side effects.
"""
from __future__ import annotations

import asyncio
from copy import deepcopy
from dataclasses import dataclass, field
from enum import Enum
import inspect
import json
import re
from typing import Any, Awaitable, Callable, Mapping

from jsonschema import Draft202012Validator, FormatChecker
from jsonschema.exceptions import SchemaError, ValidationError

from .agent_v2 import ToolCall


class Risk(str, Enum):
    READ = "read"
    WRITE = "write"
    DESTRUCTIVE = "destructive"


class ToolExecutionError(Exception):
    """Safe failure code returned to the Agent (no raw traceback)."""

    def __init__(self, code: str):
        super().__init__(code)
        self.code = code


@dataclass(frozen=True)
class ToolDefinition:
    name: str
    description: str
    input_schema: dict[str, Any]
    handler: Callable[..., Awaitable[Any]]
    risk: Risk = Risk.READ
    output_schema: dict[str, Any] | None = None


@dataclass(frozen=True)
class ToolPolicy:
    """Trusted application policy, NEVER generated by the LLM.

    (tool name, tool call ID) is a *single-run*, specific approval. For a
    destructive tool both the matching approval AND explicit allow_destructive
    are required. Binding to tenant/run is enforced in the executor ledger.
    """
    tenant_id: str
    run_id: str
    allowed_tools: frozenset[str]
    approvals: frozenset[tuple[str, str]] = frozenset()
    allow_destructive: bool = False
    max_calls: int = 8

    def __post_init__(self) -> None:
        if not self.tenant_id or not self.run_id:
            raise ValueError("Nonempty tenant_id and run_id are required")
        if type(self.max_calls) is not int or self.max_calls < 0:
            raise ValueError("max_calls must be nonnegative")


@dataclass(frozen=True)
class ToolResult:
    call_id: str
    name: str
    ok: bool
    value: Any = None
    error: str | None = None

    def observation(self) -> str:
        """Normalized tool result for the model, with an explicit error flag."""
        data = {"ok": self.ok}
        if self.ok:
            data["result"] = self.value
        else:
            data["error"] = self.error
        return json.dumps(data, ensure_ascii=False, allow_nan=False)


def _reject_external_refs(schema: Any) -> None:
    """No network/file schema retrieval from untrusted tool definitions."""
    if isinstance(schema, dict):
        for key, value in schema.items():
            if key in ("$ref", "$dynamicRef", "$recursiveRef"):
                if not isinstance(value, str) or not value.startswith("#"):
                    raise ValueError("Only local JSON Schema references are supported")
            _reject_external_refs(value)
    elif isinstance(schema, list):
        for item in schema:
            _reject_external_refs(item)


def _validator(schema: dict[str, Any], *, input_schema: bool) -> Draft202012Validator:
    if not isinstance(schema, dict):
        raise ValueError("Tool schema must be a JSON Schema object")
    if schema.get("$schema") not in (None, "https://json-schema.org/draft/2020-12/schema"):
        raise ValueError("Only JSON Schema draft 2020-12 is supported")
    if input_schema and schema.get("type") != "object":
        raise ValueError("Tool inputSchema must declare type=object")
    if len(json.dumps(schema, allow_nan=False)) > 64_000:
        raise ValueError("Tool schema too large for the teaching runtime")
    _reject_external_refs(schema)
    try:
        Draft202012Validator.check_schema(schema)
    except SchemaError as exc:
        raise ValueError("Invalid JSON Schema") from exc
    return Draft202012Validator(deepcopy(schema), format_checker=FormatChecker())


def _strict_json(raw: str, max_input_bytes: int) -> dict[str, Any]:
    if not isinstance(raw, str) or len(raw.encode("utf-8")) > max_input_bytes:
        raise ToolExecutionError("invalid_or_oversized_arguments")

    def unique_pairs(pairs):
        result = {}
        for k, v in pairs:
            if k in result:
                raise ToolExecutionError("duplicate_json_key")
            result[k] = v
        return result

    def invalid_constant(token):
        raise ToolExecutionError("invalid_json_constant")

    try:
        data = json.loads(raw, object_pairs_hook=unique_pairs,
                          parse_constant=invalid_constant)
    except (ValueError, TypeError, RecursionError) as exc:
        raise ToolExecutionError("invalid_json") from exc
    if not isinstance(data, dict):
        raise ToolExecutionError("arguments_must_be_object")
    return data


_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$")


class ToolCatalog:
    def __init__(self) -> None:
        self._definitions: dict[str, ToolDefinition] = {}
        self._inputs: dict[str, Draft202012Validator] = {}
        self._outputs: dict[str, Draft202012Validator | None] = {}

    def register(self, definition: ToolDefinition) -> None:
        if not _NAME.fullmatch(definition.name):
            raise ValueError("Tool name must be 1-128 safe ASCII characters")
        if definition.name in self._definitions:
            raise ValueError("Duplicate tool: " + definition.name)
        if not isinstance(definition.risk, Risk):
            raise ValueError("Tool risk must be explicit")
        if not inspect.iscoroutinefunction(definition.handler):
            raise ValueError("Async handler required; sync work needs a safe adapter")
        inp = _validator(definition.input_schema, input_schema=True)
        out = (_validator(definition.output_schema, input_schema=False)
               if definition.output_schema is not None else None)
        self._definitions[definition.name] = ToolDefinition(
            definition.name, definition.description, deepcopy(definition.input_schema),
            definition.handler, definition.risk, deepcopy(definition.output_schema),
        )
        self._inputs[definition.name] = inp
        self._outputs[definition.name] = out

    def get(self, name: str) -> ToolDefinition | None:
        return self._definitions.get(name)

    def specs_for(self, policy: ToolPolicy) -> list[dict[str, Any]]:
        """Offer only allowlisted tools to the model; runtime checks again."""
        return [
            {"type": "function", "function": {
                "name": definition.name,
                "description": definition.description,
                "parameters": deepcopy(definition.input_schema),
            }}
            for name, definition in self._definitions.items()
            if name in policy.allowed_tools
        ]


class AsyncToolRuntime:
    def __init__(
        self, catalog: ToolCatalog, *, max_parallel: int = 4,
        timeout_seconds: float = 3.0, max_input_bytes: int = 65536,
        max_output_bytes: int = 65536,
    ) -> None:
        if type(max_parallel) is not int or max_parallel < 1:
            raise ValueError("max_parallel must be positive")
        if not isinstance(timeout_seconds, (int, float)) or timeout_seconds <= 0:
            raise ValueError("timeout_seconds must be positive")
        if type(max_input_bytes) is not int or max_input_bytes < 1:
            raise ValueError("max_input_bytes must be positive")
        if type(max_output_bytes) is not int or max_output_bytes < 1:
            raise ValueError("max_output_bytes must be positive")
        self.catalog = catalog
        self.timeout_seconds = float(timeout_seconds)
        self.max_input_bytes = max_input_bytes
        self.max_output_bytes = max_output_bytes
        self._semaphore = asyncio.Semaphore(max_parallel)
        self._write_lock = asyncio.Lock()
        self._ledger_lock = asyncio.Lock()
        self._seen: set[tuple[str, str, str]] = set()
        self._usage: dict[tuple[str, str], int] = {}

    async def execute_one(self, call: ToolCall, policy: ToolPolicy) -> ToolResult:
        return (await self.execute_many((call,), policy))[0]

    async def execute_many(
        self, calls: tuple[ToolCall, ...] | list[ToolCall], policy: ToolPolicy,
    ) -> tuple[ToolResult, ...]:
        """Execute independent actions; preserves input ordering in results.

        The caller MUST handle dependencies; mutating calls are serialized.
        A whole batch is rejected before side effects if IDs/budget conflict.
        """
        calls = tuple(calls)
        if not calls:
            return ()
        ids = [call.id for call in calls]
        if any(not isinstance(cid, str) or not cid for cid in ids) or len(set(ids)) != len(ids):
            return tuple(ToolResult(c.id, c.name, False, error="duplicate_or_invalid_call_id")
                         for c in calls)

        run_key = (policy.tenant_id, policy.run_id)
        keys = [(policy.tenant_id, policy.run_id, call.id) for call in calls]
        async with self._ledger_lock:
            if any(key in self._seen for key in keys):
                return tuple(ToolResult(c.id, c.name, False, error="duplicate_call_id")
                             for c in calls)
            if self._usage.get(run_key, 0) + len(calls) > policy.max_calls:
                return tuple(ToolResult(c.id, c.name, False, error="tool_budget_exhausted")
                             for c in calls)
            self._seen.update(keys)
            self._usage[run_key] = self._usage.get(run_key, 0) + len(calls)

        return tuple(await asyncio.gather(
            *(self._execute(call, policy) for call in calls)
        ))

    async def _execute(self, call: ToolCall, policy: ToolPolicy) -> ToolResult:
        definition = self.catalog.get(call.name)
        if definition is None:
            return ToolResult(call.id, call.name, False, error="unknown_tool")
        if call.name not in policy.allowed_tools:
            return ToolResult(call.id, call.name, False, error="tool_not_allowed")
        if definition.risk is not Risk.READ:
            if (call.name, call.id) not in policy.approvals:
                return ToolResult(call.id, call.name, False, error="approval_required")
            if definition.risk is Risk.DESTRUCTIVE and not policy.allow_destructive:
                return ToolResult(call.id, call.name, False, error="destructive_tool_denied")
        try:
            kwargs = _strict_json(call.arguments_json, self.max_input_bytes)
            self.catalog._inputs[call.name].validate(kwargs)
        except ToolExecutionError as exc:
            return ToolResult(call.id, call.name, False, error=exc.code)
        except ValidationError:
            return ToolResult(call.id, call.name, False, error="schema_validation_failed")

        async def run_handler() -> Any:
            try:
                result = await definition.handler(**kwargs)
            except ToolExecutionError:
                raise
            except Exception as exc:
                # Do not expose arbitrary server/tool secrets to model messages.
                raise ToolExecutionError("tool_execution_failed") from exc
            try:
                serialized = json.dumps(result, allow_nan=False, ensure_ascii=False)
            except (TypeError, ValueError, RecursionError) as exc:
                raise ToolExecutionError("non_json_tool_output") from exc
            if len(serialized.encode("utf-8")) > self.max_output_bytes:
                raise ToolExecutionError("tool_output_too_large")
            validator = self.catalog._outputs[call.name]
            if validator is not None:
                try:
                    validator.validate(result)
                except ValidationError as exc:
                    raise ToolExecutionError("output_schema_validation_failed") from exc
            return result

        try:
            async with self._semaphore:
                if definition.risk is Risk.READ:
                    value = await asyncio.wait_for(run_handler(), self.timeout_seconds)
                else:
                    async with self._write_lock:
                        value = await asyncio.wait_for(run_handler(), self.timeout_seconds)
            return ToolResult(call.id, call.name, True, value=value)
        except asyncio.TimeoutError:
            # Cancellation is cooperative. An external side effect could have
            # happened even if the coroutine did not return in time.
            return ToolResult(call.id, call.name, False, error="tool_timeout_outcome_unknown")
        except ToolExecutionError as exc:
            return ToolResult(call.id, call.name, False, error=exc.code)
